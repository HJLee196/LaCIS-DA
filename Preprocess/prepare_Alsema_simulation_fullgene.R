#!/usr/bin/env Rscript

# ============================================================================
# Alsema Dataset A simulation input preparation for LaCIS-DA
# ============================================================================
#
# This script prepares the preprocessed Dataset A for the existing
# LaCIS-DA simulation code.
#
# It reorders genes using the original list of 2,000 simulation genes
# and verified symbol-to-Ensembl mappings, then removes cells with
# missing sex information.
#
# All retained genes and existing expression values are preserved.
# No additional QC, normalization, PCA, or simulation is performed.
#
# Required inputs:
#   1. Seurat RDS generated by preprocess_Alsema_DatasetA.R
#   2. metadata/simulation_genes_2000.txt
#   3. metadata/simulation_gene_mapping.csv
#   4. metadata/simulation_cell_groups_exact.csv
#      Cell-group annotations obtained through exact count matching
#      with the original LaCIS-DA dataset.
#
# Usage:
#   Rscript --vanilla prepare_Alsema_simulation_fullgene.R \
#     STAGE1_RDS metadata/simulation_genes_2000.txt \
#     metadata/simulation_gene_mapping.csv \
#     metadata/simulation_cell_groups_exact.csv OUTPUT_DIR
#
# Output:
#   A simulation-ready Seurat RDS, gene-ordering manifest,
#   and validation information.
#
# Required R packages: Matrix, SeuratObject, digest.

# ============================================================================
# Step 0 -- Configuration, dependencies and small validation helpers
# ============================================================================
arguments <- commandArgs(trailingOnly = TRUE)

if (length(arguments) != 5L) {
  stop(
    "Usage: Rscript prepare_Alsema_simulation_fullgene.R ",
    "STAGE1_RDS ORIGINAL_TXT MAPPING_CSV CELL_GROUP_CSV OUTPUT_DIR"
  )
}
for (package in c("Matrix", "SeuratObject", "digest")) {
  if (!requireNamespace(package, quietly = TRUE)) {
    stop("Required package is not installed: ", package)
  }
}
if (utils::packageVersion("SeuratObject") < "5.0.0") {
  stop("SeuratObject >= 5.0.0 is required for Assay5 construction")
}
input_paths <- normalizePath(
  arguments[1:4],
  mustWork = TRUE
)

output_dir <- arguments[5L]
if (file.exists(output_dir)) stop("Output directory exists; use a new directory")
if (!dir.create(output_dir, recursive = TRUE)) stop("Cannot create output directory")
writeLines("RUNNING", file.path(output_dir, "STATUS.txt"))

validation_checks <- data.frame(
  check = character(),
  status = character()
)

check <- function(label, condition) {
  passed <- isTRUE(condition)
  
  validation_checks <<- rbind(
    validation_checks,
    data.frame(
      check = label,
      status = if (passed) "PASS" else "FAIL"
    )
  )
  
  if (!passed) {
    stop(paste("Validation failed:", label), call. = FALSE)
  }
}

write_validation_checks <- function() {
  write.csv(
    validation_checks,
    file.path(output_dir, "validation_checks.csv"),
    row.names = FALSE
  )
}
valid_ids <- function(ids) {
  !is.null(ids) && !anyNA(ids) && all(nzchar(ids)) && !anyDuplicated(ids)
}
sha256 <- function(path) {
  digest::digest(file = path, algo = "sha256", serialize = FALSE)
}
exact_matrix <- function(left, right) {
  # Compare every entry, including implicit sparse zeros, without densifying.
  identical(dimnames(left), dimnames(right)) &&
    Matrix::nnzero(Matrix::drop0(left - right)) == 0L
}

prepare <- function() {
  # ===========================================================================
  # Step 1 -- Load and validate the four documented input artifacts
  # ===========================================================================
  # Record the SHA-256 hashes of all four input files.
  input_hashes <- vapply(
    input_paths,
    sha256,
    character(1)
  )
  
  write.csv(
    data.frame(
      role = c(
        "stage1_rds",
        "original_names",
        "public_mapping",
        "cell_groups"
      ),
      path = input_paths,
      sha256 = input_hashes
    ),
    file.path(output_dir, "input_hashes.csv"),
    row.names = FALSE
  )
  # Verify that the gene list and mapping file match the versions
  # distributed with this repository.
  # This prevents unintended changes to gene identities or ordering.
  check("original_name_file_hash", input_hashes[2L] ==
          "6ad96328dbf3de4a01c6ef1af178579256dc14f26f710f8fbe5b39e402f9a972")
  check("public_mapping_file_hash", input_hashes[3L] ==
          "d4d5984361528c0494fbaba629e80521b0bc58a6bffc99d6e2424018df625a74")

  # Load the preprocessed Seurat object and simulation gene metadata.
  # Extract the existing RNA counts, normalized data, and cell metadata.
  source_object <- readRDS(input_paths[1L])
  original_symbols <- readLines(input_paths[2L], warn = FALSE)
  mapping <- read.csv(input_paths[3L], stringsAsFactors = FALSE, na.strings = "")
  source_counts <- SeuratObject::LayerData(source_object, assay = "RNA", layer = "counts")
  source_data <- SeuratObject::LayerData(source_object, assay = "RNA", layer = "data")
  source_metadata <- source_object[[]]
  source_genes <- rownames(source_counts)
  source_cells <- colnames(source_counts)
  # Load cell-group annotations derived from exact count matching.
  cell_annotations <- read.csv(
    input_paths[4L],
    stringsAsFactors = FALSE
  )
  
  # Check the annotation file structure.
  check(
    "annotation_columns",
    identical(
      names(cell_annotations),
      c("new_cell", "original_group")
    )
  )
  
  # All annotated cells must be unique and present in Stage 1.
  check(
    "annotation_cell_ids",
    valid_ids(cell_annotations$new_cell) &&
      all(cell_annotations$new_cell %in% source_cells)
  )
  
  # Define the three original simulation groups.
  expected_groups <- c(
    "healthy_Microglia",
    "ad1_Microglia",
    "ad2_Microglia"
  )
  
  # Verify the group labels.
  check(
    "annotation_group_labels",
    !anyNA(cell_annotations$original_group) &&
      all(cell_annotations$original_group %in% expected_groups)
  )
  
  # Verify the number of annotated cells in each group.
  check(
    "annotation_group_counts",
    identical(
      as.integer(table(factor(
        cell_annotations$original_group,
        levels = expected_groups
      ))),
      c(1568L, 3245L, 7703L)
    )
  )
  
  check("source_dimensions", identical(dim(source_counts), c(28689L, 16793L)))
  check("unique_source_ids", valid_ids(source_genes) && valid_ids(source_cells))
  check("RNA_only", identical(SeuratObject::Assays(source_object), "RNA"))
  check("exact_layer_set", setequal(SeuratObject::Layers(source_object[["RNA"]]),
                                    c("counts", "data")))
  check("source_alignment", identical(dimnames(source_counts), dimnames(source_data)) &&
          identical(rownames(source_metadata), source_cells) &&
          identical(rownames(source_object), source_genes))
  check("sparse_finite_layers", inherits(source_counts, "dgCMatrix") &&
          inherits(source_data, "dgCMatrix") && all(is.finite(source_counts@x)) &&
          all(is.finite(source_data@x)))
  check("source_has_no_analysis_results", length(source_object@reductions) == 0L &&
          length(SeuratObject::VariableFeatures(source_object)) == 0L)
  
  # Validate the original 2,000-gene list and its Ensembl ID mapping.
  # The mapping must preserve the original gene order, contain 1,991
  # unique accepted IDs, and leave nine original genes unresolved.
  check("original_2000_names", length(original_symbols) == 2000L &&
          valid_ids(original_symbols))
  check("mapping_columns", identical(names(mapping),
          c("original_index", "original_symbol", "accepted_id", "mapping_status")))
  check("mapping_original_order", identical(mapping$original_index, seq_len(2000L)) &&
          identical(mapping$original_symbol, original_symbols))

  accepted <- mapping$mapping_status == "ACCEPTED"
  check("mapping_status_counts", !anyNA(mapping$mapping_status) &&
          sum(accepted) == 1991L && sum(mapping$mapping_status == "UNRESOLVED") == 9L)
  verified_genes <- mapping$accepted_id[accepted]
  check("accepted_ids_unique_and_present", valid_ids(verified_genes) &&
          all(verified_genes %in% source_genes))
  check("unresolved_ids_blank", all(is.na(mapping$accepted_id[!accepted])))

  # ===========================================================================
  # Step 2 -- Construct the full feature order using identities alone
  # ===========================================================================
  # Place the 1,991 uniquely mapped genes first, preserving their order
  # in the original simulation gene list.
  #
  # Fill the remaining nine positions among the first 2,000 genes with
  # the first nine unselected genes in the preprocessed dataset's order.
  # These are not biological replacements for the unresolved genes.
  #
  # Append all remaining genes in their original order.
  # No expression values are used to determine the gene ordering.
  unselected_genes <- source_genes[!source_genes %in% verified_genes]
  filler_genes <- head(unselected_genes, 9L)
  remaining_genes <- unselected_genes[!unselected_genes %in% filler_genes]
  ordered_genes <- c(verified_genes, filler_genes, remaining_genes)
  source_row_indices <- match(ordered_genes, source_genes)

  check("group_sizes", length(verified_genes) == 1991L && length(filler_genes) == 9L &&
          length(remaining_genes) == 26689L)
  check("complete_gene_universe", length(ordered_genes) == 28689L &&
          valid_ids(ordered_genes) && setequal(ordered_genes, source_genes))
  check("verified_relative_order", identical(ordered_genes[1:1991],
          mapping$accepted_id[accepted]))
  check("deterministic_fillers", identical(ordered_genes[1992:2000],
          head(source_genes[!source_genes %in% verified_genes], 9L)))
  check("remaining_original_order", identical(ordered_genes[2001:28689],
          source_genes[!source_genes %in% ordered_genes[1:2000]]))

  # ===========================================================================
  # Step 3 -- Remove cells with missing sex information
  # ===========================================================================
  
  # Stage 1 retains all cells, including those with missing sex metadata.
  # For simulation, exclude only cells whose sex information is missing,
  # while preserving the original order of the remaining cells.
  check("sex_metadata_present", "sex" %in% names(source_metadata))
  
  retained_cell_indices <- which(!is.na(source_metadata$sex))
  retained_metadata <- source_metadata[retained_cell_indices, , drop = FALSE]
  
  # Verify that 73 cells are excluded and 16,720 cells remain.
  check(
    "73_missing_sex_cells_removed",
    sum(is.na(source_metadata$sex)) == 73L &&
      length(retained_cell_indices) == 16720L
  )

  # ===========================================================================
  # Step 4 -- Reorder genes and select cells in both RNA layers
  # ===========================================================================
  
  # Apply the same gene ordering and cell selection to the counts and
  # normalized expression matrices.
  # Normalization is not repeated; the existing values retain the
  # library-size normalization performed on all Stage 1 retained genes.
  ordered_counts <- source_counts[
    source_row_indices,
    retained_cell_indices,
    drop = FALSE
  ]
  
  ordered_data <- source_data[
    source_row_indices,
    retained_cell_indices,
    drop = FALSE
  ]
  
  check(
    "reordered_layer_alignment",
    identical(dimnames(ordered_counts), dimnames(ordered_data))
  )

  # ===========================================================================
  # Step 5 -- Construct the simulation-ready Seurat object
  # ===========================================================================
  
  # Create an RNA assay using the reordered counts and normalized data.
  # Constructing a new assay ensures that the requested gene order is stored.
  rna <- SeuratObject::CreateAssay5Object(
    counts = ordered_counts,
    data = ordered_data,
    min.cells = 0,
    min.features = 0
  )
  
  # Create a Seurat object while preserving the original project name.
  output_object <- SeuratObject::CreateSeuratObject(
    counts = rna,
    assay = "RNA",
    meta.data = retained_metadata,
    project = SeuratObject::Project(source_object)
  )
  
  # Preserve the Stage 1 cell metadata without recalculating QC statistics.
  output_object@meta.data <- retained_metadata
  
  # Assign the original groups to cells with exact-matched annotations.
  # All other cells are labeled "unmatched".
  
  annotation_index <- match(
    colnames(output_object),
    cell_annotations$new_cell
  )
  
  simulation_groups <- rep(
    "unmatched",
    ncol(output_object)
  )
  
  has_annotation <- !is.na(annotation_index)
  
  simulation_groups[has_annotation] <-
    cell_annotations$original_group[
      annotation_index[has_annotation]
    ]
  
  names(simulation_groups) <- colnames(output_object)
  
  group_levels <- c(
    "healthy_Microglia",
    "ad1_Microglia",
    "ad2_Microglia",
    "unmatched"
  )
  
  SeuratObject::Idents(output_object) <- factor(
    simulation_groups,
    levels = group_levels
  )
  
  # Verify the assigned group sizes.
  check(
    "simulation_group_counts",
    identical(
      as.integer(table(factor(
        simulation_groups,
        levels = group_levels
      ))),
      c(1568L, 3245L, 7703L, 4204L)
    )
  )
  
  output_object@misc <- source_object@misc
  output_object@tools <- source_object@tools
  
  # Preserve gene-level metadata, if present, in the new gene order.
  source_feature_metadata <- source_object[["RNA"]][[]]
  
  if (ncol(source_feature_metadata) > 0L) {
    output_object[["RNA"]] <- SeuratObject::AddMetaData(
      output_object[["RNA"]],
      source_feature_metadata[source_row_indices, , drop = FALSE]
    )
  }
  
  # Check that the newly constructed Seurat object is valid.
  check("valid_before_save", isTRUE(methods::validObject(output_object)))

  # ===========================================================================
  # Step 6 -- Save the Seurat object and gene-ordering manifest
  # ===========================================================================
  
  # Match the reordered Ensembl IDs to the original simulation gene list.
  # Genes not included in the verified mapping receive missing values for
  # their original simulation symbol and index.
  mapping_indices <- match(ordered_genes, mapping$accepted_id)
  
  # Record the new gene order and its relationship to the Stage 1 dataset.
  manifest <- data.frame(
    new_row_index = seq_along(ordered_genes),
    source_row_index = source_row_indices,
    Ensembl_ID = ordered_genes,
    original_simulation_symbol = mapping$original_symbol[mapping_indices],
    original_simulation_index = mapping$original_index[mapping_indices],
    group = c(
      rep("VERIFIED_ORIGINAL", 1991L),
      rep("FILLER", 9L),
      rep("REMAINING", 26689L)
    ),
    mapping_provenance = ifelse(
      !is.na(mapping_indices),
      "Unambiguous symbol-to-Ensembl mapping from GEO/HGNC",
      "Existing Ensembl ID in the Stage 1 dataset"
    )
  )
  
  # Save the gene-ordering manifest.
  write.csv(
    manifest,
    file.path(output_dir, "simulation_ordered_2000_manifest.csv"),
    row.names = FALSE,
    na = ""
  )
  
  # Save the simulation-ready Seurat object.
  output_file <- file.path(
    output_dir,
    "TrackA_simulation_ordered_2000_Seurat.rds"
  )
  
  saveRDS(output_object, output_file, compress = "gzip")
  
  # Reload the saved object for validation in the next step.
  rm(output_object)
  saved_object <- readRDS(output_file)

  # ===========================================================================
  # Step 7 -- Validate the saved Seurat object
  # ===========================================================================
  
  # Reloaded counts and normalized data must preserve their original values,
  # feature order, and cell order after the Stage 2 transformations.
  saved_counts <- SeuratObject::LayerData(
    saved_object, assay = "RNA", layer = "counts"
  )
  
  saved_data <- SeuratObject::LayerData(
    saved_object, assay = "RNA", layer = "data"
  )
  
  # Verify dimensions and gene/cell ordering.
  check(
    "saved_dimensions",
    identical(dim(saved_counts), c(28689L, 16720L))
  )
  
  check(
    "saved_feature_order",
    identical(rownames(saved_object), ordered_genes) &&
      identical(rownames(saved_counts), ordered_genes)
  )
  
  check(
    "saved_layer_and_cell_order",
    identical(dimnames(saved_counts), dimnames(saved_data)) &&
      identical(colnames(saved_counts), source_cells[retained_cell_indices])
  )
  
  # Verify that no count or normalized expression values have changed.
  check("counts_exact", exact_matrix(saved_counts, ordered_counts))
  check("normalized_data_exact", exact_matrix(saved_data, ordered_data))
  
  # Verify that Stage 1 cell metadata is preserved.
  check(
    "metadata_exact",
    identical(saved_object[[]], retained_metadata)
  )
  
  # Verify that the saved identities match the assigned annotations.
  check(
    "active_identities_match_annotation",
    identical(
      unname(as.character(SeuratObject::Idents(saved_object))),
      unname(simulation_groups)
    )
  )
  
  # Verify the structural validity of the saved Seurat object.
  check("saved_object_valid", isTRUE(methods::validObject(saved_object)))

  # ===========================================================================
  # Step 8 -- Verify simulation gene selection
  # ===========================================================================
  
  # Reproduce the initial gene-selection steps used in the downstream
  # simulation code for validation.
  # Select the first 2,000 genes and retain those detected in more than
  # 33 cells. This check does not modify the saved Seurat object.
  gene.index <- 1:2000
  feature.names <- rownames(saved_object)[gene.index]
  
  selected_object <- subset(
    saved_object,
    features = feature.names
  )
  
  selected_counts <- SeuratObject::GetAssayData(
    selected_object,
    layer = "counts"
  )
  
  # Verify the order of the selected genes.
  check(
    "simulation_first2000_order",
    identical(rownames(selected_counts), ordered_genes[1:2000])
  )
  
  # Apply the detection threshold used in the simulation code.
  detection_counts <- Matrix::rowSums(selected_counts > 0)
  postfilter_genes <- rownames(selected_counts)[detection_counts > 33L]
  
  check(
    "simulation_postfilter_1940",
    length(postfilter_genes) == 1940L
  )
  
  writeLines(
    postfilter_genes,
    file.path(output_dir, "postfilter_Ensembl_ids.txt")
  )
  
  # Record input and output information.
  check(
    "input_files_unchanged",
    identical(vapply(input_paths, sha256, character(1)), input_hashes)
  )
  
  writeLines(
    sha256(output_file),
    file.path(output_dir, "output_sha256.txt")
  )
  
  writeLines(
    capture.output(sessionInfo()),
    file.path(output_dir, "session_info.txt")
  )
  
  # Save validation results and mark the run as complete.
  write_validation_checks()
  writeLines("COMPLETE", file.path(output_dir, "STATUS.txt"))
  
  cat(
    "Completed:", nrow(saved_counts), "genes x", ncol(saved_counts),
    "cells;", length(postfilter_genes),
    "genes pass the simulation detection filter.\n"
  )
  cat("Output directory:", normalizePath(output_dir), "\n")
}

tryCatch(prepare(), error = function(error) {
  write_validation_checks()
  
  writeLines(
    c("FAILED", conditionMessage(error)),
    file.path(output_dir, "STATUS.txt")
  )
  
  stop(conditionMessage(error), call. = FALSE)
})
